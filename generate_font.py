out.append("// 8x8 位图字体，索引 = ASCII - 0x20")
out.append("pub static FONT8X8: [[u8; 8]; 95] = [")
for i, r in enumerate(rows):
    vals = ", ".join("0x%02x" % b for b in r)
    out.append("    [%s], // %d (0x%02x '%s')" % (vals, i, 0x20+i, chr(0x20+i)))
out.append("];")
data = "\n".join(out)
