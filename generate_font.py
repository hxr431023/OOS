def to_bytes(lines):
    out = []
    for line in lines:
        line = (line + '.' * 8)[:8]  # 右补/截断到 8 列
        b = 0
        for x, ch in enumerate(line):
            if ch == '#':
                b |= (1 << (7 - x))
        out.append(b)
    return out

